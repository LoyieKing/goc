// gen writes the golden .gocobj files in test/gocobj/v1.0: one valid file
// and one file per verify failure. Each is a .s (hand-written machine code
// as .byte, plus the .goc.* tables from gocobj.Builder) assembled by llvm-mc.
//
//	go run ./test/gocobj/gen [-mc llvm-mc-19] [-out test/gocobj/v1.0]
package main

import (
	"bytes"
	"flag"
	"fmt"
	"log"
	"os"
	"os/exec"
	"path/filepath"

	"github.com/LoyieKing/goc/gocobj"
)

// main.add: stack check, frame, one call to runtime.helper, return.
const textAsm = `	.section .text.main.add,"ax",@progbits
	.globl main.add
	.type main.add,@function
main.add:
	.byte 0x49,0x3b,0x66,0x10        # cmp rsp,[r14+16]      0
	.byte 0x55                       # push rbp              4
	.byte 0x48,0x89,0xe5             # mov rbp,rsp           5
	.byte 0x48,0x83,0xec,0x10        # sub rsp,16            8
	.byte 0xe8                       # call runtime.helper   12
	.reloc ., R_X86_64_PLT32, runtime.helper-4
	.long 0
	.byte 0x48,0x83,0xc4,0x10        # add rsp,16            17
	.byte 0x5d                       # pop rbp               21
	.byte 0xc3                       # ret                   22
	.size main.add, .-main.add

	.section .data.main.tbl,"aw",@progbits
	.globl main.tbl
	.type main.tbl,@object
	.p2align 3
main.tbl:
	.quad 0, 0
	.size main.tbl, 16
`

func valid() *gocobj.Builder {
	return &gocobj.Builder{
		Header: gocobj.Header{Arch: gocobj.ArchAMD64, Flags: gocobj.HeaderStackChecksInCode,
			Minor: 0, Profile: "go1.24-amd64", Producer: "goc golden"},
		Files: []string{"add.c"},
		Funcs: []gocobj.Func{{
			Name: "main.add", TextSize: 23, FrameSize: 16, ArgSize: 16, ABI: gocobj.ABIInternal,
			Flags: gocobj.FuncNeedsStackCheck | gocobj.FuncHasFramePointer, StartLine: 3,
			PCValue: []gocobj.PCTable{
				{Kind: gocobj.PCSPDelta, Entries: []gocobj.PCEntry{{0, 0}, {5, 8}, {12, 24}, {21, 8}, {22, 0}}},
				{Kind: gocobj.PCLine, Entries: []gocobj.PCEntry{{0, 3}, {12, 4}, {17, 5}}},
				{Kind: gocobj.PCUnsafePoint, Entries: []gocobj.PCEntry{{0, -2}, {4, -1}}},
			},
			GC: &gocobj.GCMap{NArgs: 2, NLocals: 2, Safepoints: []gocobj.Safepoint{
				{PC: 17, Args: []byte{0x1}, Locals: []byte{0x2}}}},
		}},
		Relocs: []gocobj.Reloc{{Func: "main.add", Offset: 13, Width: 4, Kind: gocobj.RCall,
			Target: "runtime.helper", Addend: -4, Flags: gocobj.RelocSafepoint}},
		Data: []gocobj.Data{{Name: "main.tbl", Size: 16, Log2Align: 3, NBits: 2, Bitmap: []byte{0x3}}},
	}
}

// Each broken file changes one thing in valid(); the test expects the error.
var broken = map[string]func(b *gocobj.Builder){
	"bad-profile":       func(b *gocobj.Builder) { b.Header.Profile = "go1.99-amd64" },
	"bad-text-size":     func(b *gocobj.Builder) { b.Funcs[0].TextSize = 24 },
	"bad-reloc-range":   func(b *gocobj.Builder) { b.Relocs[0].Offset = 21 },
	"bad-reloc-target":  func(b *gocobj.Builder) { b.Relocs[0].Target = "runtime.nosuch" },
	"bad-no-gc-record":  func(b *gocobj.Builder) { b.Funcs[0].GC.Safepoints[0].PC = 18 },
	"bad-pc-order":      func(b *gocobj.Builder) { b.Funcs[0].PCValue[0].Entries[2].PC = 5 },
	"bad-locals-bits":   func(b *gocobj.Builder) { b.Funcs[0].GC.NLocals = 4 },
	"bad-no-stackcheck": func(b *gocobj.Builder) { b.Funcs[0].PCValue = b.Funcs[0].PCValue[:2] },
}

func main() {
	mc := flag.String("mc", "llvm-mc-19", "llvm-mc to assemble with")
	out := flag.String("out", "test/gocobj/v1.0", "output directory")
	flag.Parse()
	if err := os.MkdirAll(*out, 0o755); err != nil {
		log.Fatal(err)
	}
	write(*mc, *out, "valid", valid(), textAsm)
	for name, mut := range broken {
		b := valid()
		mut(b)
		write(*mc, *out, name, b, textAsm)
	}
}

func write(mc, dir, name string, b *gocobj.Builder, text string) {
	var s bytes.Buffer
	fmt.Fprintf(&s, "# generated by test/gocobj/gen; do not edit\n%s\n", text)
	if err := b.WriteAsm(&s); err != nil {
		log.Fatal(err)
	}
	asm := filepath.Join(dir, name+".s")
	if err := os.WriteFile(asm, s.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
	cmd := exec.Command(mc, "-triple=x86_64-unknown-linux-gnu", "-filetype=obj",
		"-o", filepath.Join(dir, name+".gocobj"), asm)
	cmd.Stderr = os.Stderr
	if err := cmd.Run(); err != nil {
		log.Fatalf("%s: %v", name, err)
	}
}
